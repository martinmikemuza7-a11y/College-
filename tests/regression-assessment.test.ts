import { parsePastPaperText } from '../server/pastPaperProcessing.js';

// Initialize in-memory database
initDb();

const PSYCHOLOGY_TEXT = `Title: The Background of Psychology: The Concept of Psychology
Author: Dr. Eleanor Vance
Copyright (c) 2024 Academic Press. All rights reserved.
Downloaded at 2024-10-12 10:30:15 from /courses/psyc101/lecture1.pdf

Psychology is defined as the scientific study of mind and behavior in humans and other animals.
Wilhelm Wundt established the first formal laboratory for psychological research at the University of Leipzig in 1879, marking the formal birth of psychology as an independent academic discipline.
Structuralism, formulated by Edward Titchener, aimed to analyze the basic elements of conscious mental experience through systematic self-observation known as introspection.
Functionalism, pioneered by William James, investigated the adaptive functions of consciousness and how behavioral processes enable organisms to survive and adapt to their environments.
Behaviorism, founded by John B. Watson and expanded by B.F. Skinner, argued that psychology must focus strictly on observable behavior rather than unobservable conscious states.
Cognitive psychology emerged in the mid-twentieth century to explore mental processes including perception, memory, problem-solving, and language acquisition.`;

const CPP_TEXT = `Title: Advanced C++ Systems Programming
Copyright 2024 DevPress Publishing. All rights reserved.
Generated by compiler tools at 2024-11-05 08:22:11

Resource Acquisition Is Initialization (RAII) is a core C++ programming idiom where resource allocation is tied to object lifetime, ensuring automatic cleanup during stack unwinding.
A virtual destructor is required in a base class with virtual functions to ensure that derived class destructors are correctly invoked when deleting an object through a base pointer.
Smart pointers, including std::unique_ptr and std::shared_ptr, manage dynamic memory automatically through ownership semantics to prevent memory leaks and dangling pointers.
Pointer dereferencing using the asterisk operator accesses the value stored at the memory address held by the pointer.
Move semantics, introduced in C++11 using rvalue references, enable the efficient transfer of resources between objects without deep copying.`;

const BIOLOGY_TEXT = `Title: Cell Biology and Cellular Respiration
Copyright (c) 2024 BioScience Educational Media.

Chemiosmosis is the movement of ions across a semipermeable membrane down their electrochemical gradient, used to generate ATP during cellular respiration.
The mitochondrial electron transport chain consists of four multi-protein complexes located in the inner mitochondrial membrane that transfer electrons from NADH and FADH2 to oxygen.
ATP synthase is the enzymatic complex that catalyzes the synthesis of ATP from ADP and inorganic phosphate, powered by the proton-motive force.
The phospholipid bilayer forms a selectively permeable membrane barrier with hydrophilic phosphate heads facing aqueous environments and hydrophobic fatty acid tails sequestered inside.`;

const METADATA_ONLY_TEXT = `The Background of Psychology: The Concept of Psychology
Copyright © 2024 Global Education Ltd. All rights reserved.
Page 1 of 1
SlideMaster Template v2.1
Downloaded on 2024-09-01 by student_448`;

describe('Study Buddy AI - Educational Assessment & Grounding Regression Suite', () => {

  it('Batch planner uses the total requested count across sequential batches', () => {
    assert.strictEqual(calculateQuestionBatchSize(10, 0), 5);
    assert.strictEqual(calculateQuestionBatchSize(10, 5), 5);
    assert.strictEqual(calculateQuestionBatchSize(10, 8), 2);
    assert.strictEqual(calculateQuestionBatchSize(10, 10), 0);
  });

  it('Question deduplication catches punctuation changes but preserves different concepts', () => {
    assert.strictEqual(
      isDuplicateQuestion(
        'Which of the following accurately describes structuralism?',
        ['Which of the following accurately describes structuralism']
      ),
      true
    );
    assert.strictEqual(
      isDuplicateQuestion(
        'Structuralism aimed to analyze conscious mental experience through systematic self-observation.',
        ['Structuralism aimed to analyze conscious mental experience through systematic self-observation!']
      ),
      true
    );
    assert.strictEqual(isDuplicateQuestion('What is functionalism?', ['What is structuralism?']), false);
  });

  it('Fallback generator avoids questions already delivered in an earlier batch', () => {
    const sourceChunk = {
      chunkId: 'chk_dedup_test',
      documentId: 'doc_dedup_test',
      filename: 'psychology_lecture.txt',
      courseId: 'course_dedup_test',
      folderId: null,
      ownerId: 'usr_test',
      pageOrSlide: 1,
      chunkIndex: 0,
      text: sanitizeEducationalContent(PSYCHOLOGY_TEXT),
      sourceExcerpt: PSYCHOLOGY_TEXT.slice(0, 220),
      tokenEstimate: 50,
    };
    const firstBatch = generateDomainGroundedQuestions([sourceChunk], 5, 'medium', undefined, 'notes_based');
    const secondBatch = generateDomainGroundedQuestions(
      [sourceChunk],
      5,
      'medium',
      undefined,
      'notes_based',
      undefined,
      firstBatch.map((question) => question.question)
    );
    assert.ok(firstBatch.length > 0, 'First batch should contain questions');
    for (const question of secondBatch) {
      assert.strictEqual(
        isDuplicateQuestion(question.question, firstBatch.map((item) => item.question)),
        false,
        'Continuation must not repeat a previously delivered question'
      );
    }
  });

  it('Past-paper extraction preserves original question stems and MCQ options without inventing questions', () => {
    const extracted = parsePastPaperText(
      [
        'Question 1: Which operator accesses the value stored at a pointer address?',
        'A. Address-of operator',
        'B. Dereference operator',
        'C. Scope resolution operator',
        'D. Conditional operator',
        'Question 2: Explain the purpose of a function in C++ (5 marks)',
      ].join('\n'),
      'C++_2025_exam.txt'
    );

    assert.strictEqual(extracted.questions.length, 2);
    assert.strictEqual(extracted.questions[0].questionNumber, '1');
    assert.strictEqual(extracted.questions[0].prompt, 'Which operator accesses the value stored at a pointer address?');
    assert.deepStrictEqual(extracted.questions[0].options, [
      'Address-of operator',
      'Dereference operator',
      'Scope resolution operator',
      'Conditional operator',
    ]);
    assert.strictEqual(extracted.questions[0].type, 'multiple_choice');
    assert.strictEqual(extracted.questions[1].prompt, 'Explain the purpose of a function in C++ (5 marks)');
    assert.strictEqual(extracted.questions[1].allocatedMarks, 5);

    const subquestions = parsePastPaperText(
      '1. Functions\n1(a) Define a function.\n1(b) State one benefit of using functions.\n2. Explain function overloading.',
      'subquestions.txt'
    );
    assert.deepStrictEqual(subquestions.questions.map((question) => question.questionNumber), ['1', '1(a)', '1(b)', '2']);
    assert.strictEqual(subquestions.questions[1].prompt, 'Define a function.');
    assert.strictEqual(subquestions.questions[2].prompt, 'State one benefit of using functions.');

    const unnumbered = parsePastPaperText(
      'This is an ordinary paragraph about functions and variables, not an actual exam question.',
      'not_a_paper.txt'
    );
    assert.strictEqual(unnumbered.questions.length, 0, 'Do not fabricate exam questions from ordinary paragraphs');
  });

  it('Metadata Sanitizer: Strips copyright, timestamps, file paths, and templates', () => {
    const sanitized = sanitizeEducationalContent(PSYCHOLOGY_TEXT);
    
    assert.strictEqual(sanitized.includes('Copyright (c) 2024'), false, 'Copyright notice should be stripped');
    assert.strictEqual(sanitized.includes('All rights reserved'), false, 'All rights reserved should be stripped');
    assert.strictEqual(sanitized.includes('2024-10-12 10:30:15'), false, 'Timestamp should be stripped');
    assert.strictEqual(sanitized.includes('/courses/psyc101/lecture1.pdf'), false, 'File path should be stripped');
    assert.strictEqual(sanitized.includes('Psychology is defined as'), true, 'Substantive content must be preserved');
  });

  it('Substantive Content Detector: Accurately identifies educational content vs metadata-only noise', () => {
    assert.strictEqual(isSubstantiveEducationalContent(PSYCHOLOGY_TEXT), true, 'Full psychology lecture is substantive');
    assert.strictEqual(isSubstantiveEducationalContent(CPP_TEXT), true, 'C++ lecture is substantive');
    assert.strictEqual(isSubstantiveEducationalContent(BIOLOGY_TEXT), true, 'Biology lecture is substantive');
    assert.strictEqual(isSubstantiveEducationalContent(METADATA_ONLY_TEXT), false, 'Metadata-only text should not be substantive');
    assert.strictEqual(isSubstantiveEducationalContent('The Background of Psychology: The Concept of Psychology'), false, 'Title alone is not substantive');
  });

  it('Anti-Contamination Validator: Correctly flags cross-domain pollutants', () => {
    const psychSource = 'Psychology is the scientific study of mind and behavior. Wilhelm Wundt established introspection and structuralism.';
    
    // Contaminated with deep learning/NLP
    assert.strictEqual(isCrossDomainContaminated('It operates independently of attention parameters.', psychSource), true);
    assert.strictEqual(isCrossDomainContaminated('It replaces linear projections with unscaled quadratic convolutions.', psychSource), true);
    assert.strictEqual(isCrossDomainContaminated('It acts solely on decoding outputs.', psychSource), true);

    // Contaminated with biology
    assert.strictEqual(isCrossDomainContaminated('It catalyzes ATP synthesis via the mitochondrial electron transport chain.', psychSource), true);

    // Authentic psychology statement
    assert.strictEqual(isCrossDomainContaminated('It analyzes the basic elements of conscious mental experience through introspection.', psychSource), false);
  });

  it('Regression Test (Reproduce & Verify Fixed): Psychology document generates authentic psychology questions without attention parameters or quadratic convolutions', async () => {
    // 1. Ingest Psychology Material
    const psychMat: Material = {
      id: `mat_test_psych_${Date.now()}`,
      courseId: 'crs_test_suite',
      folderId: null,
      ownerId: 'usr_test',
      title: 'The Background of Psychology: The Concept of Psychology',
      filename: 'The_Background_of_Psychology_The_Concept_of_Psychology.pdf',
      mimeType: 'application/pdf',
      sizeBytes: 1024,
      extractedTextLength: 0,
      chunkCount: 0,
      status: 'processing',
      hasEmbeddings: false,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    db.data.materials.push(psychMat);
    const extracted = await extractContent(psychMat.filename, 'text/plain', undefined, PSYCHOLOGY_TEXT);
    await processAndIndexMaterial(psychMat, extracted);

    // 2. Generate Practice Questions for Psychology
    const quizBatch = await generateQuizQuestions({
      courseId: 'crs_test_suite',
      selectedDocumentIds: [psychMat.id],
      questionCount: 3,
      difficulty: 'medium',
      questionTypes: ['multiple_choice'],
    });

    assert.ok(quizBatch.questions.length >= 1, 'Should generate at least 1 question');

    for (const q of quizBatch.questions) {
      assert.strictEqual(q.type, 'multiple_choice');
      assert.ok(q.options && q.options.length === 4, 'MCQ must have exactly 4 options');

      const allOptionsText = q.options.join(' ').toLowerCase();

      // STRICT REGRESSION CHECKS: The forbidden NLP / Transformer distractors MUST NOT appear!
      assert.strictEqual(allOptionsText.includes('attention parameter'), false, 'MUST NOT contain attention parameters');
      assert.strictEqual(allOptionsText.includes('quadratic convolution'), false, 'MUST NOT contain quadratic convolutions');
      assert.strictEqual(allOptionsText.includes('decoding output'), false, 'MUST NOT contain decoding outputs');
      assert.strictEqual(allOptionsText.includes('scaled dot-product'), false, 'MUST NOT contain scaled dot-product');
      assert.strictEqual(allOptionsText.includes('mitochondria'), false, 'MUST NOT contain biology terms in psychology');

      // Verify that options are labelled A, B, C, D
      assert.ok(q.options[0].startsWith('A. '), 'Option 1 should start with A.');
      assert.ok(q.options[1].startsWith('B. '), 'Option 2 should start with B.');
      assert.ok(q.options[2].startsWith('C. '), 'Option 3 should start with C.');
      assert.ok(q.options[3].startsWith('D. '), 'Option 4 should start with D.');

      // Verify correct answer is one of the 4 options
      assert.ok(q.options.includes(q.correctAnswer), 'Correct answer must be one of the 4 options');

      // Verify question is grounded in psychology concepts
      const qLower = q.question.toLowerCase() + ' ' + q.correctAnswer.toLowerCase();
      const hasPsychConcept =
        qLower.includes('psychology') ||
        qLower.includes('wundt') ||
        qLower.includes('mind') ||
        qLower.includes('behavior') ||
        qLower.includes('structuralism') ||
        qLower.includes('functionalism') ||
        qLower.includes('introspection') ||
        qLower.includes('cognitive') ||
        qLower.includes('watson');
      assert.ok(hasPsychConcept, `Question must test psychology concepts, got: "${q.question}"`);

      // Verify no meta-phrases
      assert.strictEqual(/^According to/i.test(q.question), false, 'Question must not start with According to...');
    }
  });

  it('Contrasting Subject 2 (C++ Programming): Strictly isolated to C++ concepts without psychology or biology leaks', async () => {
    const cppMat: Material = {
      id: `mat_test_cpp_${Date.now()}`,
      courseId: 'crs_test_suite',
      folderId: null,
      ownerId: 'usr_test',
      title: 'Advanced C++ Systems Programming',
      filename: 'cpp_systems.docx',
      mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
      sizeBytes: 1024,
      extractedTextLength: 0,
      chunkCount: 0,
      status: 'processing',
      hasEmbeddings: false,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    db.data.materials.push(cppMat);
    const extracted = await extractContent(cppMat.filename, 'text/plain', undefined, CPP_TEXT);
    await processAndIndexMaterial(cppMat, extracted);

    const quizBatch = await generateQuizQuestions({
      courseId: 'crs_test_suite',
      selectedDocumentIds: [cppMat.id],
      questionCount: 3,
      difficulty: 'hard',
      questionTypes: ['multiple_choice'],
    });

    for (const q of quizBatch.questions) {
      const allText = (q.question + ' ' + (q.options?.join(' ') || '')).toLowerCase();

      // Verify C++ domain concepts present
      const hasCppConcept =
        allText.includes('raii') ||
        allText.includes('destructor') ||
        allText.includes('pointer') ||
        allText.includes('smart pointer') ||
        allText.includes('move semantics') ||
        allText.includes('resource');
      assert.ok(hasCppConcept, 'C++ quiz must test C++ concepts');

      // Verify complete absence of Psychology and Biology terms
      assert.strictEqual(allText.includes('wundt'), false, 'C++ quiz must not mention Wundt');
      assert.strictEqual(allText.includes('introspection'), false, 'C++ quiz must not mention introspection');
      assert.strictEqual(allText.includes('chemiosmosis'), false, 'C++ quiz must not mention chemiosmosis');
      assert.strictEqual(allText.includes('mitochondria'), false, 'C++ quiz must not mention mitochondria');
      assert.strictEqual(allText.includes('attention parameter'), false, 'C++ quiz must not mention attention parameters');
    }
  });

  it('Contrasting Subject 3 (Cell Biology): Strictly isolated to Biology concepts without C++ or NLP leaks', async () => {
    const bioMat: Material = {
      id: `mat_test_bio_${Date.now()}`,
      courseId: 'crs_test_suite',
      folderId: null,
      ownerId: 'usr_test',
      title: 'Cell Biology and Cellular Respiration',
      filename: 'cell_biology.pptx',
      mimeType: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
      sizeBytes: 1024,
      extractedTextLength: 0,
      chunkCount: 0,
      status: 'processing',
      hasEmbeddings: false,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    db.data.materials.push(bioMat);
    const extracted = await extractContent(bioMat.filename, 'text/plain', undefined, BIOLOGY_TEXT);
    await processAndIndexMaterial(bioMat, extracted);

    const quizBatch = await generateQuizQuestions({
      courseId: 'crs_test_suite',
      selectedDocumentIds: [bioMat.id],
      questionCount: 3,
      difficulty: 'medium',
      questionTypes: ['multiple_choice'],
    });

    for (const q of quizBatch.questions) {
      const allText = (q.question + ' ' + (q.options?.join(' ') || '')).toLowerCase();

      // Verify Biology domain concepts present
      const hasBioConcept =
        allText.includes('chemiosmosis') ||
        allText.includes('atp') ||
        allText.includes('mitochondrial') ||
        allText.includes('electron transport') ||
        allText.includes('phospholipid');
      assert.ok(hasBioConcept, 'Biology quiz must test biology concepts');

      // Verify complete absence of C++ and Psychology terms
      assert.strictEqual(allText.includes('virtual destructor'), false, 'Biology quiz must not mention virtual destructor');
      assert.strictEqual(allText.includes('pointer dereference'), false, 'Biology quiz must not mention pointer dereference');
      assert.strictEqual(allText.includes('wundt'), false, 'Biology quiz must not mention Wundt');
      assert.strictEqual(allText.includes('behaviorism'), false, 'Biology quiz must not mention behaviorism');
      assert.strictEqual(allText.includes('attention parameter'), false, 'Biology quiz must not mention attention parameters');
    }
  });

  it('Insufficient / Metadata-Only Document: Rejects generation with a clear educational limitation error', async () => {
    const metaMat: Material = {
      id: `mat_test_meta_${Date.now()}`,
      courseId: 'crs_test_suite',
      folderId: null,
      ownerId: 'usr_test',
      title: 'The Background of Psychology: The Concept of Psychology',
      filename: 'metadata_only.pdf',
      mimeType: 'application/pdf',
      sizeBytes: 50,
      extractedTextLength: 0,
      chunkCount: 0,
      status: 'processing',
      hasEmbeddings: false,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    db.data.materials.push(metaMat);
    const extracted = await extractContent(metaMat.filename, 'text/plain', undefined, METADATA_ONLY_TEXT);
    await processAndIndexMaterial(metaMat, extracted);

    // Attempting to generate questions from metadata-only should fail with informative error
    await assert.rejects(
      async () => {
        await generateQuizQuestions({
          courseId: 'crs_test_suite',
          selectedDocumentIds: [metaMat.id],
          questionCount: 3,
        });
      },
      (err: Error) => {
        assert.ok(
          err.message.includes('insufficient') || err.message.includes('substantive'),
          `Error message should explain insufficient educational content, got: "${err.message}"`
        );
        return true;
      }
    );
  });
});
